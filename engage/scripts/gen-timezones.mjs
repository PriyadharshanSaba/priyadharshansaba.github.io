// Generates src/timezones.ts: IANA timezone name -> the countries that use it.
//   node scripts/gen-timezones.mjs [/path/to/zoneinfo]      (default: /usr/share/zoneinfo)
// Needs zone.tab and tzdata.zi from the IANA tz database (public domain). The output is committed, so this
// only needs re-running occasionally (timezone changes are rare). Not part of the build.
//
// Why aliases matter: Chrome and Node report India as "Asia/Calcutta", not "Asia/Kolkata". Without folding
// links (L lines in tzdata.zi) into their target, every Indian Chrome visitor would look like a mismatch.
// Countries that share a zone (Liechtenstein uses Europe/Zurich, Croatia uses Europe/Belgrade) are grouped
// by following the same links, so they are not flagged either.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = process.argv[2] ?? "/usr/share/zoneinfo";
const zi = readFileSync(join(dir, "tzdata.zi"), "utf8").split("\n");
const tab = readFileSync(join(dir, "zone.tab"), "utf8").split("\n");

const version = (zi[0].match(/version\s+(\S+)/) ?? [])[1] ?? "unknown";
const zones = new Set();                 // real zones ("Z name ...")
const links = new Map();                 // alias -> target ("L target alias")
for (const line of zi) {
  if (line.startsWith("Z ")) zones.add(line.split(" ")[1]);
  else if (line.startsWith("L ")) { const [, target, alias] = line.split(" "); links.set(alias, target); }
}
function canonical(name) {
  for (let i = 0; i < 10 && links.has(name); i++) name = links.get(name);
  return name;
}

// canonical zone -> countries (from zone.tab: "CC <TAB> coords <TAB> Zone/Name")
const groups = new Map();
for (const line of tab) {
  if (!line || line.startsWith("#")) continue;
  const [cc, , zone] = line.split("\t");
  if (!/^[A-Z]{2}$/.test(cc) || !zone) continue;
  const key = canonical(zone);
  if (!groups.has(key)) groups.set(key, new Set());
  groups.get(key).add(cc);
}

// Every name a browser might report (real zones and their aliases) that has a country.
const names = new Set([...zones, ...links.keys()]);
for (const line of tab) { const z = line.split("\t")[2]; if (z) names.add(z); }
const out = {};
for (const n of [...names].sort()) {
  const g = groups.get(canonical(n));
  if (g) out[n] = [...g].sort().join(" ");
}

const body = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
const file = `// GENERATED by scripts/gen-timezones.mjs. Do not edit by hand.
// Source: IANA tz database ${version} (zone.tab + tzdata.zi), public domain.
// Maps a timezone name, including old aliases such as Asia/Calcutta, to the countries that use it (space-separated).
export const TZDATA_VERSION = ${JSON.stringify(version)};
export const ZONE_COUNTRIES: Record<string, string> = {
${body}
};
`;
const target = fileURLToPath(new URL("../src/timezones.ts", import.meta.url));
writeFileSync(target, file);
console.log(`tzdata ${version}: wrote ${Object.keys(out).length} zone names to src/timezones.ts (${(file.length / 1024).toFixed(0)} KB)`);
